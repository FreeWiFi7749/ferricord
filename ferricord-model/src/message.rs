/// Represents a message sent in a channel.
#[derive(Clone, Debug, Deserialize, Serialize)]
pub struct Message {
    /// ID of the message.
    pub id: MessageId,
    /// ID of the channel the message was sent in.
    pub channel_id: ChannelId,
    /// The author of this message.
    pub author: User,
    /// Contents of the message.
    pub content: String,
    /// When this message was sent.
    pub timestamp: String,
    /// When this message was edited (or null if never).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub edited_timestamp: Option<String>,
    /// Whether this was a TTS message.
    pub tts: bool,
    /// Whether this message mentions everyone.
    pub mention_everyone: bool,
    /// Users specifically mentioned in the message.
    #[serde(default)]
    pub mentions: Vec<User>,
    /// Roles specifically mentioned in this message.
    #[serde(default)]
    pub mention_roles: Vec<RoleId>,
    /// Channels specifically mentioned in this message.
    #[serde(default)]
    pub mention_channels: Vec<ChannelMention>,
    /// Any attached files.
    #[serde(default)]
    pub attachments: Vec<Attachment>,
    /// Any embedded content.
    #[serde(default)]
    pub embeds: Vec<Embed>,
    /// Reactions to the message.
    #[serde(default)]
    pub reactions: Vec<Reaction>,
    /// Used for validating a message was sent.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub nonce: Option<serde_json::Value>,
    /// Whether this message is pinned.
    pub pinned: bool,
    /// If the message is generated by a webhook, this is the webhook's ID.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub webhook_id: Option<WebhookId>,
    /// Type of message.
    #[serde(rename = "type")]
    pub kind: MessageType,
    /// Sent with Rich Presence-related chat embeds.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub activity: Option<MessageActivity>,
    /// Sent with Rich Presence-related chat embeds.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub application: Option<MessageApplication>,
    /// If the message is an Interaction or application-owned webhook.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub application_id: Option<UserId>,
    /// Data showing the source of a crosspost, channel follow add, pin, or reply message.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub message_reference: Option<MessageReference>,
    /// Message flags.
    #[serde(default)]
    pub flags: u32,
    /// The message associated with the message_reference.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub referenced_message: Option<Box<Message>>,
    /// Sent if the message is a response to an Interaction.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub interaction: Option<MessageInteraction>,
    /// The thread that was started from this message.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub thread: Option<Channel>,
    /// Sent if the message contains components like buttons, action rows, or other interactive components.
    #[serde(default)]
    pub components: Vec<Component>,
    /// Sent if the message contains stickers.
    #[serde(default)]
    pub sticker_items: Vec<StickerItem>,
    /// A generally increasing integer that represents the approximate position of the message in a thread.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub position: Option<u32>,
    /// The guild ID of the message.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub guild_id: Option<GuildId>,
    /// Member properties for this message's author.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub member: Option<Member>,
}

impl Message {
    /// Returns a URL that links to this message.
    pub fn jump_url(&self) -> String {
        match self.guild_id {
            Some(guild_id) => format!(
                "https://discord.com/channels/{}/{}/{}",
                guild_id, self.channel_id, self.id
            ),
            None => format!(
                "https://discord.com/channels/@me/{}/{}",
                self.channel_id, self.id
            ),
        }
    }

    /// Returns true if this message is a system message.
    pub fn is_system(&self) -> bool {
        !matches!(self.kind, MessageType::Default | MessageType::Reply)
    }
}

