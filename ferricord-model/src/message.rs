/// Represents a file attached to a message.
#[derive(Clone, Debug, Deserialize, Serialize)]
pub struct Attachment {
    /// Attachment ID.
    pub id: AttachmentId,
    /// Name of file attached.
    pub filename: String,
    /// Description for the file.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    /// The attachment's media type.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub content_type: Option<String>,
    /// Size of file in bytes.
    pub size: u64,
    /// Source URL of file.
    pub url: String,
    /// A proxied URL of file.
    pub proxy_url: String,
    /// Height of file (if image).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub height: Option<u32>,
    /// Width of file (if image).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub width: Option<u32>,
    /// Whether this attachment is ephemeral.
    #[serde(default)]
    pub ephemeral: bool,
    /// The duration of the audio file (currently for voice messages).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub duration_secs: Option<f64>,
    /// Base64 encoded bytearray representing a sampled waveform.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub waveform: Option<String>,
    /// Attachment flags.
    #[serde(default)]
    pub flags: u32,
}

impl Attachment {
    /// Returns true if this attachment is an image.
    pub fn is_image(&self) -> bool {
        self.content_type
            .as_ref()
            .map(|ct| ct.starts_with("image/"))
            .unwrap_or(false)
    }

    /// Returns true if this attachment is a video.
    pub fn is_video(&self) -> bool {
        self.content_type
            .as_ref()
            .map(|ct| ct.starts_with("video/"))
            .unwrap_or(false)
    }

    /// Returns true if this attachment is audio.
    pub fn is_audio(&self) -> bool {
        self.content_type
            .as_ref()
            .map(|ct| ct.starts_with("audio/"))
            .unwrap_or(false)
    }

    /// Returns true if this attachment is spoilered.
    pub fn is_spoiler(&self) -> bool {
        self.filename.starts_with("SPOILER_")
    }
}

/// Represents an embed in a message.
#[derive(Clone, Debug, Default, Deserialize, Serialize)]
pub struct Embed {
    /// Title of embed.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub title: Option<String>,
    /// Type of embed (always "rich" for webhook embeds).
    #[serde(rename = "type", skip_serializing_if = "Option::is_none")]
    pub kind: Option<String>,
    /// Description of embed.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    /// URL of embed.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub url: Option<String>,
    /// Timestamp of embed content.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub timestamp: Option<String>,
    /// Color code of the embed.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub color: Option<u32>,
    /// Footer information.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub footer: Option<EmbedFooter>,
    /// Image information.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub image: Option<EmbedImage>,
    /// Thumbnail information.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub thumbnail: Option<EmbedThumbnail>,
    /// Video information.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub video: Option<EmbedVideo>,
    /// Provider information.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub provider: Option<EmbedProvider>,
    /// Author information.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub author: Option<EmbedAuthor>,
    /// Fields information.
    #[serde(default)]
    pub fields: Vec<EmbedField>,
}

impl Embed {
    /// Create a new embed builder.
    pub fn new() -> Self {
        Self::default()
    }

    /// Set the title of the embed.
    pub fn title(mut self, title: impl Into<String>) -> Self {
        self.title = Some(title.into());
        self
    }

    /// Set the description of the embed.
    pub fn description(mut self, description: impl Into<String>) -> Self {
        self.description = Some(description.into());
        self
    }

    /// Set the URL of the embed.
    pub fn url(mut self, url: impl Into<String>) -> Self {
        self.url = Some(url.into());
        self
    }

    /// Set the color of the embed.
    pub fn color(mut self, color: u32) -> Self {
        self.color = Some(color);
        self
    }

    /// Add a field to the embed.
    pub fn field(
        mut self,
        name: impl Into<String>,
        value: impl Into<String>,
        inline: bool,
    ) -> Self {
        self.fields.push(EmbedField {
            name: name.into(),
            value: value.into(),
            inline,
        });
        self
    }
}

